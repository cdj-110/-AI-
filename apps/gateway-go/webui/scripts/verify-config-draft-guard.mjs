import assert from 'node:assert/strict'
import {createServer} from 'vite'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright')
const server=await createServer({optimizeDeps:{entries:['scripts/fixtures/config-draft-guard.html']},server:{host:'127.0.0.1',port:0},logLevel:'error'})
let browser
try{
 await server.listen()
 browser=await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL||'chrome'})
 const page=await browser.newPage({viewport:{width:1600,height:1000}}),errors=[]
 await page.routeWebSocket('**/api/ws',()=>{})
 page.on('pageerror',error=>errors.push(error.message))
 const base=`http://127.0.0.1:${server.httpServer.address().port}/scripts/fixtures/config-draft-guard.html`
 for(const protocol of ['modbus-rtu','opcda','iec104','modbus-tcp-slave','iec61850-mms-server']){
  await page.goto(base+'?protocol='+protocol)
  await page.locator('.legacy-resource-workspace').waitFor()
  await page.waitForTimeout(200)
  const baseline=await page.evaluate(()=>window.draftState())
  assert.ok(Array.isArray(baseline.forwardDevices),'missing list must be initialized before baseline')
  await page.locator('#leave').click()
  await page.waitForFunction(()=>document.querySelector('#left').textContent==='1')
  await page.locator('#device').click()
  await page.locator('.legacy-device-workspace').waitFor()
  await page.waitForTimeout(200)
  assert.deepEqual(await page.evaluate(()=>window.draftState()),baseline,'browsing device must not rewrite configuration')
  await page.locator('#leave').click()
  await page.waitForFunction(()=>document.querySelector('#left').textContent==='2')
  await page.locator('#channel').click()
  await page.locator('.legacy-channel-workspace').waitFor()
  await page.locator('#resource').click()
  await page.locator('#edit').click()
  await page.locator('#run').click()
  await page.waitForTimeout(100)
  assert.equal(await page.locator('.unsaved-config-modal').count(),0,'no-edit mode toggle must not prompt')
  await page.locator('#edit').click()
  const name=page.locator('.legacy-resource-workspace .legacy-field-grid input').first()
  await name.fill('实际编辑名称')
  await page.locator('#device').click()
  await page.getByRole('heading',{name:'尚有未保存的修改',exact:true}).waitFor()
  await page.getByRole('button',{name:'继续编辑',exact:true}).click()
  assert.equal(await page.locator('.legacy-resource-workspace').count(),1,'dirty selection must remain on original resource')
  await page.locator('#resource').click()
  await page.locator('#leave').click()
  await page.getByRole('heading',{name:'尚有未保存的修改',exact:true}).waitFor()
  await page.getByRole('button',{name:'继续编辑',exact:true}).click()
  assert.equal(await name.inputValue(),'实际编辑名称','navigation must not erase user edits or reset baseline')
  await name.fill('RS485-1')
  await page.locator('#leave').click()
  await page.waitForFunction(()=>document.querySelector('#left').textContent==='3')
  await page.locator('.legacy-resource-workspace').getByRole('button',{name:'重新加载',exact:true}).click()
  await page.waitForTimeout(150)
  await page.locator('#leave').click()
  await page.waitForFunction(()=>document.querySelector('#left').textContent==='4')
  await name.fill('需要保存的修改')
  await page.locator('#run').click()
  await page.locator('.unsaved-config-modal').waitFor()
  await page.getByRole('button',{name:'放弃修改并运行',exact:true}).click()
  await page.waitForTimeout(200)
  await page.locator('#leave').click()
  await page.waitForFunction(()=>document.querySelector('#left').textContent==='5')
  assert.equal(await name.inputValue(),'RS485-1')
  await page.locator('#edit').click()
  await page.locator('#channel').click()
  const isForward=['modbus-tcp-slave','iec61850-mms-server'].includes(protocol)
  const nextProtocol=isForward?'iec104-server':protocol==='modbus-rtu'?'opcda':'modbus-rtu'
  await page.locator('.channel-field-grid select').first().selectOption(nextProtocol)
  const edited=await page.evaluate(()=>window.draftState())
  assert.equal((isForward?edited.forwardDevices:edited.devices)[0].protocol,nextProtocol,'explicit protocol edits must still synchronize devices')
  await page.locator('#leave').click()
  await page.getByRole('heading',{name:'尚有未保存的修改',exact:true}).waitFor()
  await page.getByRole('button',{name:'继续编辑',exact:true}).click()
  console.log(`${protocol}: automatic defaults and browsing clean; actual/protocol edits protected; revert/reload/discard clean`)
 }
 assert.deepEqual(errors,[])
}finally{await browser?.close();await server.close()}
