import assert from 'node:assert/strict'
import {createServer} from 'vite'
import vue from '@vitejs/plugin-vue'
import {mkdir} from 'node:fs/promises'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright')
const server=await createServer({configFile:false,plugins:[vue()],optimizeDeps:{entries:['scripts/fixtures/dlt645-layout.html']},server:{host:'127.0.0.1',port:0},logLevel:'error'})
let browser
try {
  await server.listen()
  browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHANNEL?{channel:process.env.PLAYWRIGHT_CHANNEL}:{})})
  const page=await browser.newPage({viewport:{width:1920,height:1000}})
  const errors=[]
  const standardItem={key:'status-word-1',name:'电表运行状态字 1',category:'状态',di2007:'04000501',valueFormat:'binary',dataLength:2,decimals:0,dataType:'uint64',unit:'',access:'read'}
  await page.route('**/api/dlt645/dictionary',route=>route.fulfill({json:{items:[standardItem]}}))
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/scripts/fixtures/dlt645-layout.html`)
  await page.getByRole('button',{name:/点位配置/}).click({timeout:10000}).catch(async error=>{
    console.log('page errors:',errors,'page html:',(await page.locator('body').innerHTML()).slice(0,6000))
    throw error
  })
  const table=page.locator('.dlt645-point-table table')
  await table.waitFor()
  assert.deepEqual(await table.locator('tbody .dlt645-type-tag').allTextContents(),['64位浮点数','64位无符号整数','字符串','结构化数据','—'])
  assert.equal(await table.locator('tbody .dlt645-type-tag').first().getAttribute('title'),'float64')
  assert.equal(await table.locator('tbody tr').first().locator('td').nth(8).textContent(),'BCD · 4字节')
  assert.equal(await table.locator('tbody select').count(),0,'run mode must not show dropdown arrows')
  assert.equal(await table.locator('tbody tr').last().locator('td').nth(6).textContent(),'待识别')
  async function checkBounds(){
    const indexCells=await table.locator('.point-sheet-index').evaluateAll(cells=>cells.map(cell=>({width:cell.getBoundingClientRect().width,align:getComputedStyle(cell).textAlign})))
    assert.ok(indexCells.every(cell=>cell.width>=42&&cell.width<=50&&cell.align==='center'),'sequence column must stay compact and centered: '+JSON.stringify(indexCells))
    const checks=await table.locator('.point-sheet-select').evaluateAll(cells=>cells.map(cell=>{
      const input=cell.querySelector('input[type="checkbox"]'),a=cell.getBoundingClientRect(),b=input.getBoundingClientRect()
      return {offset:Math.abs((a.left+a.right-b.left-b.right)/2),width:a.width,height:b.height}
    }))
    assert.ok(checks.every(check=>check.offset<1.1),'header and row checkboxes must be centered in the same column: '+JSON.stringify(checks))
    assert.ok(checks.every(check=>check.width<=42),'selection column must start compact, not inherit the 88px data-cell minimum')
    const invalid=await table.evaluate(table=>Array.from(table.querySelectorAll('td input:not([type=checkbox]), td select, .dlt645-type-tag')).filter(el=>{
      const a=el.getBoundingClientRect(),b=el.closest('td').getBoundingClientRect()
      return a.width>0&&(a.left<b.left-1||a.right>b.right+1)
    }).map(el=>el.outerHTML))
    assert.deepEqual(invalid,[],'controls must not overlap adjacent columns')
    assert.equal(await table.locator('.dlt645-type-tag').evaluateAll(tags=>tags.some(tag=>tag.scrollWidth>tag.clientWidth+1)),false,'actual type labels must remain fully readable, even before hover initialization')
  }
  await checkBounds()
  await mkdir('artifacts/dlt645-layout',{recursive:true})
  await page.screenshot({path:'artifacts/dlt645-layout/running.png',fullPage:true})
  await page.locator('#mode').click()
  await table.locator('thead .point-sheet-select input').check()
  assert.equal(await table.locator('tbody .point-sheet-select input:checked').count(),5)
  await table.locator('tbody .point-sheet-select input').first().uncheck()
  assert.equal(await table.locator('thead .point-sheet-select input').isChecked(),false)
  await table.locator('thead .point-sheet-select input').check()
  await table.locator('thead .point-sheet-select input').uncheck()
  assert.equal(await table.locator('tbody .point-sheet-select input:checked').count(),0)
  assert.equal(await table.locator('tbody .dlt645-access-column select').count(),5)
  assert.equal(await table.locator('tbody .dlt645-type-column select').count(),5)
  assert.equal(await table.getByLabel('数据项 / 格式').count(),5)
  const first=table.locator('tbody tr').first()
  await first.getByLabel('倍率',{exact:true}).fill('0.01')
  await first.getByLabel('偏移',{exact:true}).fill('-2.5')
  const scaledPoint=JSON.parse(await page.locator('#point-configs').textContent())[0]
  assert.equal(scaledPoint.scale,0.01)
  assert.equal(scaledPoint.offset,-2.5)
  const format=first.getByLabel('数据项 / 格式'),type=first.getByLabel('值类型')
  await format.selectOption('item:status-word-1')
  await page.waitForTimeout(200)
  assert.equal(await type.inputValue(),'uint64')
  assert.equal(await type.isDisabled(),true,'standard item types must follow the dictionary')
  let config=JSON.parse(await page.locator('#point-configs').textContent())[0]
  assert.equal(config.dlt645.itemKey,'status-word-1')
  assert.equal(config.dlt645.dataLength,2)
  assert.equal(config.dlt645.dataIdentifier,'')
  assert.equal(config.dataType,'uint64')
  assert.equal(config.decimals,0)
  assert.equal(config.unit,'')
  await format.selectOption('format:signed-bcd')
  await page.waitForTimeout(200)
  assert.equal(await type.inputValue(),'float64')
  config=JSON.parse(await page.locator('#point-configs').textContent())[0]
  assert.equal(config.dlt645.itemKey,'')
  assert.equal(config.dlt645.dataIdentifier,'04000501','manual conversion keeps the dictionary DI')
  await type.selectOption('string')
  await page.waitForTimeout(200)
  assert.equal(await format.inputValue(),'format:ascii','type selection must change the decoder')
  assert.equal(JSON.parse(await page.locator('#point-configs').textContent())[0].dataType,'string')
  await checkBounds()
  await table.locator('tbody .dlt645-access-column select').first().selectOption('read_write')
  await table.locator('tbody .dlt645-unit-column input').first().fill('kWh')
  const header=table.locator('th.dlt645-access-column')
  await header.hover()
  const box=await header.boundingBox()
  await page.mouse.move(box.x+box.width-2,box.y+15)
  await page.mouse.down()
  await page.mouse.move(box.x+box.width+58,box.y+15,{steps:6})
  await page.mouse.up()
  await page.locator('#mode').hover()
  await page.waitForTimeout(350)
  assert.ok(Math.abs((await header.boundingBox()).width-box.width-60)<3,'resize must survive live refresh')
  await checkBounds()
  await page.screenshot({path:'artifacts/dlt645-layout/configuration.png',fullPage:true})
  await page.setViewportSize({width:1280,height:900})
  await checkBounds()
  await page.locator('#mode').click()
  assert.equal(await table.locator('tbody .dlt645-access-column').first().textContent(),'读写')
  assert.equal(await first.locator('.dlt645-scale-column').textContent(),'0.01')
  assert.equal(await first.locator('.dlt645-offset-column').textContent(),'-2.5')
  assert.equal(await table.locator('.dlt645-scale-column input,.dlt645-offset-column input').count(),0,'run mode shows read-only scaling values')
  await checkBounds()
  await page.locator('#mode').click()
  await page.getByRole('button',{name:'新增点位',exact:true}).click()
  const added=table.locator('tbody tr').last()
  assert.equal(await added.getByLabel('数据项 / 格式').inputValue(),'format:bcd')
  assert.equal(await added.getByLabel('值类型').inputValue(),'float64')
  await added.getByLabel('数据项 / 格式').selectOption('item:status-word-1')
  await page.waitForTimeout(250)
  assert.equal(await added.getByLabel('值类型').inputValue(),'uint64')
  await page.locator('#mode').click()
  assert.equal(await table.locator('tbody select').count(),0)
  assert.equal(await added.locator('td').nth(8).textContent(),'电表运行状态字 1')
  assert.deepEqual(errors,[])
  console.log('DL/T 645: actual types, unknown version, run/config modes, control bounds, resize and live refresh passed')
} finally {
  await browser?.close()
  await server.close()
}
