import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright')
const browser=await chromium.launch({headless:true,channel:'chrome'})
try{
 const ctx=await browser.newContext({viewport:{width:1366,height:768}})
 const login=await ctx.request.post('http://192.168.1.214:8088/login',{form:{username:'admin',password:process.env.WK_EG100_WEB_PASSWORD,next:'/'}})
 assert.ok(!login.url().includes('/login')&&!login.url().includes('/change-password'))
 const page=await ctx.newPage(),writes=[],errors=[]
 page.on('pageerror',error=>errors.push(error.message))
 await page.route('**/api/**',route=>{if(route.request().method()!=='GET'){writes.push(route.request().url());return route.abort()}return route.continue()})
 const [response]=await Promise.all([page.waitForResponse(r=>new URL(r.url()).pathname==='/api/alarms'),page.goto('http://192.168.1.214:8088/?page=alarms')])
 const snapshot=await response.json(),entry=page.getByRole('button',{name:'打开告警面板',exact:true})
 await page.locator('.alarm-view').waitFor()
 if(snapshot.activeCount>0)await entry.locator('b').waitFor()
 await entry.click()
 const panel=page.getByRole('dialog',{name:'告警面板',exact:true})
 await panel.waitFor();assert.deepEqual(await panel.boundingBox(),{x:0,y:0,width:1366,height:768})
 const eligible=snapshot.active.filter(e=>!e.acknowledged&&e.popupEnabled!==false)
 if(eligible.length){
  const card=panel.locator('.alarm-panel-card').first();await card.waitFor()
  const name=await card.getAttribute('aria-label'),selected=panel.getByRole('article',{name,exact:true})
  const before=await selected.boundingBox(),handle=await selected.locator('.alarm-card-drag').boundingBox()
  await page.mouse.move(handle.x+70,handle.y+12);await page.mouse.down();await page.mouse.move(handle.x+160,handle.y+180,{steps:8});await page.mouse.up()
  const after=await selected.boundingBox()
  assert.ok(after.y-before.y>100,'actual card moves inside panel')
  const area=await panel.locator('.panel-list').boundingBox()
  assert.ok(after.x>=area.x&&after.y>=area.y&&after.x+after.width<=area.x+area.width&&after.y+after.height<=area.y+area.height)
  await page.waitForResponse(r=>new URL(r.url()).pathname==='/api/alarms')
  if(await selected.count())assert.ok(Math.abs((await selected.boundingBox()).y-after.y)<2,'poll preserves actual position')
  await mkdir('artifacts/alarm-panel',{recursive:true});await page.screenshot({path:'artifacts/alarm-panel/eg100-dragged-card.png'})
  await panel.getByRole('button',{name:'重置布局',exact:true}).click()
  assert.equal(await panel.locator('.floating').count(),0)
  console.log('Live card drag, bounds, poll position and reset verified')
 }else console.log('No eligible live reminders: drag covered by local browser regression')
 await panel.locator('.panel-close').click();await panel.waitFor({state:'detached'})
 const view=page.locator('.alarm-view')
 await view.getByRole('button',{name:/告警规则/}).click();await view.getByRole('button',{name:'新增规则',exact:true}).click()
 const editor=page.getByRole('dialog',{name:'告警规则',exact:true});await editor.waitFor()
 assert.ok(await editor.locator('.alarm-form').evaluate(el=>el.scrollHeight<=el.clientHeight+1),'live rule editor fits without scrolling')
 const save=await editor.getByRole('button',{name:'确定',exact:true}).boundingBox()
 assert.ok(save.y+save.height<=768)
 await mkdir('artifacts/alarm-rule-layout',{recursive:true});await page.screenshot({path:'artifacts/alarm-rule-layout/eg100.png'})
 await editor.getByRole('button',{name:'取消',exact:true}).click()
 assert.deepEqual(writes,[]);assert.deepEqual(errors,[])
 console.log('Live compact editor and visible buttons verified; draft cancelled, no business writes')
}finally{await browser.close()}
