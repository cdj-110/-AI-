import assert from 'node:assert/strict'
import {formatPointValueDisplay as format} from '../src/pointValueDisplay.ts'
for(const value of [43.3,433*0.1,43.300000000000004])assert.equal(format(value),'43.3')
assert.equal(format(0.1+0.2),'0.3')
assert.equal(format(43.3,2),'43.30')
assert.equal(format(43.3,0),'43.3','automatic precision must not round to an integer')
assert.equal(format(1234567890123456),'1234567890123456')
assert.equal(format(18446744073709552000,2,'18446744073709551615'),'18446744073709551615')
assert.equal(format('43.300000000000004'),'43.300000000000004','strings must remain exact')
assert.equal(format(false),'false')
assert.equal(format([1,2]),'[1,2]')
assert.equal(format(null),'-')
assert.equal(format(NaN),'-')
assert.equal(format(43.3,100),'43.3','invalid decimals must not break rendering')
assert.equal(format(0.00000000000123),'1.23e-12')
assert.equal(format(1.23456789012345),'1.23456789012345')
assert.equal(format(438*0.1),'43.8')
assert.equal(format(438*0.1+16,2),'59.80')
assert.equal(format(438*0.1+16,0),'59.8')
assert.equal(format(1.2345678901234567),'1.2345678901234567','keep genuine precision')
assert.equal(format(1/3),String(1/3))
assert.equal(format(Number.MIN_VALUE),String(Number.MIN_VALUE))
const nested={values:[438*0.1,true,'43.800000000000004']}
assert.equal(format(nested),'{"values":[43.8,true,"43.800000000000004"]}')
assert.equal(nested.values[0],438*0.1,'display must not mutate readings')
console.log('Point value display passed: floating tails, explicit/automatic precision, exact large integers, strings and invalid inputs.')
