import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright')
const browser=await chromium.launch({headless:true,channel:'chrome'})
try{
 const ctx=await browser.newContext({viewport:{width:1366,height:768}}),writes=[],errors=[]
 const login=await ctx.request.post('http://192.168.1.214:8088/login',{form:{username:'admin',password:process.env.WK_EG100_WEB_PASSWORD,next:'/'}})
 assert.ok(!login.url().includes('/login')&&!login.url().includes('/change-password'))
 ctx.on('page',page=>page.on('pageerror',e=>errors.push(e.message)))
 await ctx.route('**/api/**',route=>{if(route.request().method()!=='GET'){writes.push(route.request().url());return route.abort()}return route.continue()})
 const page=await ctx.newPage()
 await page.goto('http://192.168.1.214:8088/?page=alarms')
 const view=page.locator('.alarm-view');await view.waitFor()
 await view.getByRole('button',{name:'声音设置',exact:true}).click()
 const sound=page.getByRole('region',{name:'告警声音设置'});await sound.waitFor()
 const warning=await sound.getByLabel('警告告警颜色').inputValue()
 await sound.getByLabel('严重提示音',{exact:true}).selectOption('bell')
 await sound.getByLabel('严重告警音量').fill('20')
 await sound.getByLabel('严重告警颜色').evaluate(el=>{el.value='#7c3aed';el.dispatchEvent(new Event('input',{bubbles:true}))})
 await page.waitForFunction(()=>document.documentElement.style.getPropertyValue('--alarm-critical-color').trim()==='#7c3aed')
 assert.equal(await sound.getByLabel('警告告警颜色').inputValue(),warning)
 await sound.getByRole('button',{name:'严重试听',exact:true}).click()
 await sound.getByRole('button',{name:'停止试听',exact:true}).click()
 await sound.getByLabel('告警声音开关').selectOption('off')
 await mkdir('artifacts/alarm-level-colors',{recursive:true})
 await page.screenshot({path:'artifacts/alarm-level-colors/eg100-settings.png'})
 await page.reload();await view.waitFor();await view.getByRole('button',{name:'声音设置',exact:true}).click();await sound.waitFor()
 assert.equal(await sound.getByLabel('严重告警颜色').inputValue(),'#7c3aed')
 assert.equal(await sound.getByLabel('严重提示音',{exact:true}).inputValue(),'bell')
 assert.equal(await sound.getByLabel('严重告警音量').inputValue(),'20')
 assert.equal(await sound.getByLabel('警告告警颜色').inputValue(),warning)
 const entry=page.getByRole('button',{name:'打开告警面板',exact:true})
 await entry.click()
 const panel=page.getByRole('dialog',{name:'告警面板',exact:true});await panel.waitFor()
 await panel.getByRole('switch',{name:'新标签页打开告警面板'}).click()
 await panel.locator('.panel-close').click();await panel.waitFor({state:'detached'})
 const opened=ctx.waitForEvent('page');await entry.click();const child=await opened
 await child.waitForURL('**/*alarmPanel=1*')
 await child.getByRole('dialog',{name:'告警面板',exact:true}).waitFor()
 await child.waitForFunction(()=>document.documentElement.style.getPropertyValue('--alarm-critical-color').trim()==='#7c3aed')
 assert.equal(await child.getByRole('switch',{name:'新标签页打开告警面板'}).getAttribute('aria-checked'),'true')
 assert.equal(await panel.count(),0)
 await child.screenshot({path:'artifacts/alarm-level-colors/eg100-independent.png'})
 assert.deepEqual(writes,[]);assert.deepEqual(errors,[])
 console.log('Live EG100: per-level sound/color, preview, persistence, isolated levels, new-tab panel and cross-tab palette verified. No server writes; isolated browser preferences only.')
}finally{await browser.close()}
