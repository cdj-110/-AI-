const fs = require('fs')
const path = require('path')
const assert = require('node:assert/strict')
const { parse, compileScript, compileTemplate } = require('@vue/compiler-sfc')
const file = path.resolve(__dirname, '../src/packages/components/Decorates/Mores/CirclePoint/index.vue')
const source = fs.readFileSync(file, 'utf8')
const { descriptor, errors } = parse(source, { filename: file })
assert.deepEqual(errors, [])
compileScript(descriptor, { id: 'circle-scale' })
const compiled = compileTemplate({ source: descriptor.template.content, filename: file, id: 'circle-scale', compilerOptions: { expressionPlugins: ['typescript'] } })
assert.deepEqual(compiled.errors, [])
assert.match(source, /viewBox="0 0 110 110"/)
assert.match(source, /preserveAspectRatio="xMidYMid meet"/)
assert.equal((source.match(/cx="55"/g) || []).length, 2)
assert.match(source, /circle-point-blur-\$\{props.chartConfig.id\}/)
// meet 缩放随内容尺寸变化，并保持圆形；普通容器拖动未改变内容尺寸时不缩放。
const diameter = (width, height) => 100 * Math.min(width / 110, height / 110)
assert.equal(diameter(220, 220), 200)
assert.equal(diameter(55, 55), 50)
assert.equal(diameter(220, 110), 100)
assert.equal(diameter(110, 220), 100)
console.log('PASS: CirclePoint SFC, proportional scaling, non-square viewport and per-instance filter')
