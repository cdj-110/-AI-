const assert = require('node:assert/strict');
const { historyRetention, shiftHistoryMonths, protectHistoryReduction } = require('../dist/subscriptions/history-retention');
const { DevicesService } = require('../dist/devices/devices.service');
const { SubscriptionsService } = require('../dist/subscriptions/subscriptions.service');
const { HistoryCleanupService } = require('../dist/subscriptions/history-cleanup.service');
const DAY = 86400000;
async function main() {
  assert.equal(shiftHistoryMonths(new Date('2024-03-31T02:30:00+08:00'), -1).toISOString(), '2024-02-28T18:30:00.000Z');
  assert.equal(shiftHistoryMonths(new Date('2025-03-31T02:30:00+08:00'), -1).toISOString(), '2025-02-27T18:30:00.000Z');
  const now = new Date('2026-10-13T12:00:00+08:00');
  const plans = [{historyRetentionDays:7,historyRetentionMonths:0}, {historyRetentionDays:0,historyRetentionMonths:6}, {historyRetentionDays:0,historyRetentionMonths:9}, {historyRetentionDays:0,historyRetentionMonths:12}];
  assert.equal(historyRetention(plans[0], null, now).earliestAt.getTime(), now.getTime()-7*DAY);
  assert.equal(historyRetention(plans[1], null, now).earliestAt.toISOString(), '2026-04-13T04:00:00.000Z');
  assert.equal(historyRetention(plans[2], null, now).earliestAt.toISOString(), '2026-01-13T04:00:00.000Z');
  assert.equal(historyRetention(plans[3], null, now).earliestAt.toISOString(), '2025-10-13T04:00:00.000Z');
  const sub = {expiresAt:new Date('2027-01-01T00:00:00Z'),addonHistoryMonths:6,historyAddonExpiresAt:new Date('2026-10-12T00:00:00Z')};
  const expiredAddon = historyRetention(plans[1], sub, now);
  assert.equal(expiredAddon.addonMonths, 0);
  assert.equal(expiredAddon.graceEndsAt.toISOString(), '2026-10-19T00:00:00.000Z');
  assert.ok(expiredAddon.queryEarliestAt < expiredAddon.earliestAt);
  const afterGrace=historyRetention(plans[1],sub,new Date('2026-10-19T00:00:00Z'));
  assert.equal(afterGrace.graceEndsAt,null);
  assert.equal(afterGrace.queryEarliestAt.getTime(),afterGrace.earliestAt.getTime());
  assert.equal(historyRetention(plans[1],{...sub,expiresAt:new Date('2028-01-01')},now).addonMonths,0,'renewal does not extend old addon');
  const before = historyRetention(plans[3], null, now), after=historyRetention(plans[1],null,now);
  const protection=protectHistoryReduction(before,after,now);
  assert.equal(historyRetention({...plans[1],...protection},null,now).queryEarliestAt.getTime(),before.queryEarliestAt.getTime(),'unsubscribed plan users also get 7-day protection');
  assert.equal(protection.historyGraceEndsAt.getTime(),now.getTime()+7*DAY);
  assert.deepEqual(protectHistoryReduction(after,before,now),{});
  assert.equal(historyRetention(plans[1],{...sub,...protection},new Date(now.getTime()+7*DAY)).graceEndsAt,null,'expiry boundary is exclusive');
  const subscriptions = Object.create(SubscriptionsService.prototype);
  assert.throws(()=>subscriptions.cleanAddon({resourceType:'HISTORY',quantity:3,priceCents:0,pricePending:false}),/price|请填写/);
  assert.throws(()=>subscriptions.cleanAddon({resourceType:'HISTORY',quantity:6,priceCents:100}),/3个月/);
  assert.throws(()=>subscriptions.validateHistoryPlan(0,0),/历史保存/);
  assert.throws(()=>subscriptions.validateHistoryPlan(7,6),/历史保存/);
  subscriptions.prisma={tenant:{findUnique:async()=>({id:'tenant-a'})},tenantSubscription:{findUnique:async()=>({id:'sub-a',status:'ACTIVE',expiresAt:new Date('2099-01-01'),plan:{}})},subscriptionOrder:{findFirst:async()=>null},quotaAddon:{findUnique:async()=>({enabled:true,pricePending:true,resourceType:'HISTORY',quantity:3,priceCents:0})}};
  await assert.rejects(subscriptions.submitOrderForTenant({sub:'user-a',tenantId:'tenant-a'},'tenant-a',{orderType:'EXPANSION',addonId:'history',paymentMethod:'ALIPAY'}),/价格待定/);
  let updated;
  const tx={$queryRaw:async()=>[],tenantSubscription:{findUnique:async()=>({id:'sub-a',planId:'basic',expiresAt:new Date('2099-01-01'),addonHistoryMonths:0}),update:async({data})=>(updated=data,{id:'sub-a',...data})},subscriptionPlan:{findUnique:async()=>plans[1]}};
  subscriptions.recordEntitlement=async()=>{};
  await subscriptions.activateOrder(tx,{tenantId:'tenant-a',orderType:'EXPANSION',addon:{resourceType:'HISTORY',quantity:3},historyAddonMonths:6,addonQuantity:2},now);
  assert.equal(updated.addonHistoryMonths,6);
  assert.equal(updated.historyAddonExpiresAt.toISOString(),'2099-01-01T00:00:00.000Z');
  const actor={role:'TENANT_ADMIN',tenantId:'tenant-a',sub:'user-a'};
  const id='aaaaaaaa-aaaa-4aaa-aaaa-aaaaaaaaaaaa';
  const devices=Object.create(DevicesService.prototype); let calls=[];
  devices.prisma={device:{findMany:async()=>[{id,tenantId:'tenant-a',name:'设备',metrics:[{identifier:'temperature',name:'温度'}]}]}};
  devices.subscriptionLimits={history:async()=>historyRetention(plans[0],null,new Date())};
  devices.timescale={query:async(sql,args)=>{calls.push({sql,args});return{rows:sql.includes('COUNT(')?[{total:'0'}]:[]}}};
  const pairs=[{value1:id,value2:'temperature'}];
  await assert.rejects(devices.telemetryHistoryTable(actor,pairs,'2020-01-01 00:00:00','2020-01-02 00:00:00'),/保存期限/);
  assert.equal(calls.length,0,'expired query never reaches telemetry database');
  await assert.rejects(devices.telemetryHistoryTable(actor,pairs,undefined,'2099-01-01 00:00:00'),/未来/);
  await assert.rejects(devices.telemetryHistoryTable(actor,Array(21).fill(pairs[0])),/20/);
  await assert.rejects(devices.telemetryHistoryTable(actor,[{value1:id,value2:'disabled'}]),/点位/);
  await devices.telemetryHistoryTable(actor,pairs,undefined,undefined,1,10);
  assert.equal(calls.length,2);assert.equal(calls[0].args.length,9);assert.equal(calls[1].args.length,7);
  assert.match(calls[0].sql,/LIMIT \$8 OFFSET \$9/);assert.match(calls[1].sql,/retention/);
  assert.equal(JSON.parse(calls[1].args[6])[0].deviceId,id);
  devices.prisma.device.findMany=async()=>[];
  await assert.rejects(devices.telemetryHistoryTable(actor,pairs),/无权访问/);
  const cleanup=Object.create(HistoryCleanupService.prototype);
  let touched=false; cleanup.prisma={tenant:{findMany:async()=>{touched=true;return[]}}};
  const enabled=process.env.HISTORY_CLEANUP_ENABLED, activation=process.env.HISTORY_CLEANUP_ACTIVATED_AT;
  try {
    process.env.HISTORY_CLEANUP_ENABLED='false';await cleanup.run(now);assert.equal(touched,false);
    process.env.HISTORY_CLEANUP_ENABLED='true';process.env.HISTORY_CLEANUP_ACTIVATED_AT='invalid';await cleanup.run(now);assert.equal(touched,false);
    process.env.HISTORY_CLEANUP_ACTIVATED_AT=now.toISOString();await cleanup.run(now);assert.equal(touched,false);
  } finally { if(enabled===undefined)delete process.env.HISTORY_CLEANUP_ENABLED;else process.env.HISTORY_CLEANUP_ENABLED=enabled;if(activation===undefined)delete process.env.HISTORY_CLEANUP_ACTIVATED_AT;else process.env.HISTORY_CLEANUP_ACTIVATED_AT=activation; }
  console.log('PASS history retention: natural months, tiers, expansion expiry, 7-day grace, query authorization/parameters, cleanup off and activation gates. No database writes.');
}
main().catch(e=>{console.error(e);process.exitCode=1});
