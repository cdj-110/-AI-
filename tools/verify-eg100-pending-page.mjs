import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const base='http://192.168.1.214:8088',out=process.env.WK_EG100_QA_OUTPUT||'artifacts/eg100-activation-entry-20260917';
let browser;
try {
 browser=await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL||'chrome'});
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const publicStatus=await context.request.get(base+'/api/license/status');
 assert.equal(publicStatus.status(),200);
 const identity=await publicStatus.json();
 assert.equal(identity.authenticated,false);
 assert.equal(identity.license.restricted,true);
 assert.equal(identity.initialActivationAllowed,true,'Gateway is not eligible for first activation');
 const loginEntry=await context.request.get(base+'/login',{maxRedirects:0});
 assert.equal(loginEntry.status(),303);
 assert.equal(loginEntry.headers().location,'/','Unlicensed gateway displayed login page');
 assert.ok(!JSON.stringify(identity).includes('/userdata/'),'public status leaked internal paths');
 for(const path of ['/api/config','/api/status','/api/session'])assert.equal((await context.request.get(base+path)).status(),401,`Public business route: ${path}`);
 for(const method of ['POST','PUT'])assert.equal((await context.request.fetch(base+'/api/activation',{method,data:{content:'test-only'}})).status(),401,'Anonymous activation import allowed');
 const page=await context.newPage(),business=[],errors=[];
 page.on('request',r=>{const p=new URL(r.url()).pathname;if(p.startsWith('/api/')&&!['/api/session','/api/license/status'].includes(p))business.push(p)});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'/');
 await page.getByRole('heading',{name:'网关待激活'}).waitFor();
 assert.equal(await page.getByRole('button',{name:'退出登录'}).count(),0);
 assert.equal(await page.locator('.app-shell').count(),0);
 assert.equal(await page.getByRole('button',{name:'导入授权文件'}).isEnabled(),true);
 const header=await page.locator('.activation-header').boundingBox();
 assert.equal(header.height,56,'Desktop header differs from gateway shell');
 assert.equal(header.x,0);
 assert.equal(header.width,1440);
 assert.equal(await page.locator('.activation-header').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(255, 255, 255)');
 await page.getByRole('button',{name:'复制设备身份'}).click();
 await page.getByRole('status').filter({hasText:'设备身份已复制'}).waitFor();
 await mkdir(out,{recursive:true});
 await page.screenshot({path:out+'/eg100-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 const mobileHeader=await page.locator('.activation-header').boundingBox();
 assert.equal(mobileHeader.height,56,'Mobile header differs from gateway shell');
 assert.equal(mobileHeader.x,0);
 assert.equal(mobileHeader.width,390);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:out+'/eg100-mobile.png',fullPage:true});
 await page.waitForTimeout(5500);
 assert.deepEqual(business,[],'Business API requests started while inactive');
 const chooserPromise=page.waitForEvent('filechooser');
 await page.getByRole('button',{name:'导入授权文件'}).click();
 const chooser=await chooserPromise;
 assert.equal(await page.getByRole('dialog',{name:'管理员身份验证'}).count(),0,'First activation requested administrator credentials');
 await chooser.setFiles([]); // Cancel file selection; do not activate or change configuration.
 assert.equal(page.url(),base+'/','First activation left activation page');
 assert.equal((await (await context.request.get(base+'/api/license/status')).json()).authenticated,false,'First activation created a login session');
 await page.getByRole('heading',{name:'网关待激活'}).waitFor();
 assert.equal(await page.getByRole('button',{name:'导入授权文件'}).isEnabled(),true);
 const invalidPreview=await context.request.post(base+'/api/activation/initial',{data:{content:JSON.stringify({enabled:true,licenseVersion:2,licenseSequence:1,signature:'invalid',hardwareId:identity.hardwareIdentity.id,chipUsid:identity.secureChipIdentity.usid,sn:'INVALID-TEST',deviceSecret:'CHANGE_ME_LOCAL_ONLY',broker:'tcp://127.0.0.1:1883'})}});
 assert.equal(invalidPreview.status(),400,'Invalid signed first activation was not rejected');
 assert.equal((await (await context.request.get(base+'/api/license/status')).json()).initialActivationAllowed,true,'Invalid preflight modified activation state');
 assert.deepEqual(errors,[]);
 const result={realGatewayPageVerified:true,fullWidthWhiteHeader:true,headerHeight:56,anonymousEntry:true,identityCopyWorks:true,anonymousReplacementProtected:true,unlicensedLoginRedirectsToActivation:true,firstActivationWithoutCredentials:true,invalidSignedPreflightRejected:true,fileChooserWorks:true,activationUnchanged:true,noBusinessShell:true,noBusinessRequests:true,importButtonEnabled:true,mobileNoOverflow:true,pageErrors:errors};
 await writeFile(out+'/page-verification.json',JSON.stringify(result,null,2));
 console.log(JSON.stringify(result));
} finally {await browser?.close();}
